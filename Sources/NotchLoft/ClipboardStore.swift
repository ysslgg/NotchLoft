import AppKit

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var date = Date()
    var pinned = false
}

/// Historique du presse-papier (texte). Seuls les éléments épinglés sont conservés sur disque.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var copiedID: UUID?

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxUnpinned = 30
    private let fileURL: URL
    // Marqueurs standard des gestionnaires de mots de passe : on ne les enregistre jamais.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NotchLoft", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("pinned-clipboard.json")
        if let data = try? Data(contentsOf: fileURL),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    func setEnabled(_ on: Bool) {
        timer?.invalidate()
        timer = nil
        guard on else { return }
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        guard let raw = pb.string(forType: .string) else { return }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        add(String(text.prefix(5000)))
    }

    private func add(_ text: String) {
        let wasPinned = items.first { $0.text == text }?.pinned ?? false
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, pinned: wasPinned), at: 0)
        normalize()
    }

    private func normalize() {
        let pinned = items.filter(\.pinned)
        var rest = items.filter { !$0.pinned }
        if rest.count > maxUnpinned { rest = Array(rest.prefix(maxUnpinned)) }
        items = pinned + rest
        save()
    }

    private func save() {
        let pinned = items.filter(\.pinned)
        if pinned.isEmpty {
            try? FileManager.default.removeItem(at: fileURL)
        } else if let data = try? JSONEncoder().encode(pinned) {
            try? data.write(to: fileURL, options: .atomic)
        }
    }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChange = pb.changeCount
        copiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.copiedID == item.id { self?.copiedID = nil }
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle()
        normalize()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Efface l'historique ; les éléments épinglés restent.
    func clearUnpinned() {
        items.removeAll { !$0.pinned }
        save()
    }
}
